// Compiles content/notes/*.md into TypeScript modules consumed by the Angular app.
// README.md, files starting with "_" (template, ideas) and notes with `published: false` are never shipped.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'content/notes');
const outDir = join(root, 'src/app/features/notes/data');
const routesFile = join(root, 'prerender-routes.txt');

const LOCALES = ['fr', 'en'];
const FILE_PATTERN = /^([a-z0-9-]+)\.(fr|en)\.md$/;

function parseFrontmatter(raw, file) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing frontmatter block`);

  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const sep = line.indexOf(':');
    if (sep === -1) throw new Error(`${file}: invalid frontmatter line "${line}"`);
    const key = line.slice(0, sep).trim();
    let value = line.slice(sep + 1).trim();

    if (value.startsWith('[') && value.endsWith(']')) {
      value = value
        .slice(1, -1)
        .split(',')
        .map(v => v.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean);
    } else if (value === 'true' || value === 'false') {
      value = value === 'true';
    } else {
      value = value.replace(/^["']|["']$/g, '');
    }
    data[key] = value;
  }
  return { data, body: match[2] };
}

function readingTime(text) {
  const words = text.split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 220));
}

const notes = [];
const content = {};

for (const file of readdirSync(contentDir).sort()) {
  if (file.startsWith('_') || file === 'README.md' || !file.endsWith('.md')) continue;

  const nameMatch = file.match(FILE_PATTERN);
  if (!nameMatch) throw new Error(`${file}: expected "<slug>.<fr|en>.md"`);
  const [, slug, locale] = nameMatch;

  const { data, body } = parseFrontmatter(readFileSync(join(contentDir, file), 'utf8'), file);
  if (data.published !== true) continue;

  for (const field of ['title', 'summary', 'date']) {
    if (!data[field]) throw new Error(`${file}: missing "${field}"`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date)) throw new Error(`${file}: date must be YYYY-MM-DD`);

  notes.push({
    slug,
    locale,
    title: data.title,
    summary: data.summary,
    date: data.date,
    tags: Array.isArray(data.tags) ? data.tags : [],
    readingTime: readingTime(body),
  });
  content[`${locale}/${slug}`] = marked.parse(body, { async: false });
}

notes.sort((a, b) => b.date.localeCompare(a.date));

const header = '// AUTO-GENERATED by scripts/build-notes.mjs from content/notes. Do not edit.\n';

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'notes.generated.ts'),
  `${header}import { NoteMeta } from '../models/note.model';\n\n` +
    `export const NOTES: NoteMeta[] = ${JSON.stringify(notes, null, 2)};\n`
);
writeFileSync(
  join(outDir, 'notes-content.generated.ts'),
  `${header}export const NOTES_CONTENT: Record<string, string> = ${JSON.stringify(content, null, 2)};\n`
);

const slugs = [...new Set(notes.map(n => n.slug))];
const routes = LOCALES.flatMap(locale => slugs.map(slug => `/${locale}/notes/${slug}`));
writeFileSync(routesFile, routes.join('\n') + (routes.length ? '\n' : ''));

console.log(`[notes] ${notes.length} published note(s), ${routes.length} prerender route(s)`);
